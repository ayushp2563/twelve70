function main() {
  console.log(`⏳ Expanding CSV with ${NEW_COMBINATIONS.length} curated combinations…`);
  
  if (!fs.existsSync(CSV_PATH)) {
    console.error(`❌ CSV path not found: ${CSV_PATH}`);
    process.exit(1);
  }

  const newRows: string[] = [];
  const now = '2026-05-20 18:00:00';

  for (const [top, topOuter, bottom, outerwear, footwear] of NEW_COMBINATIONS) {
    const id = crypto.randomUUID();
    // Format: id,top_color,top_outer_color,bottom_color,outerwear_color,footwear_color,created_at,updated_at,is_active
    const row = `${id},${top},${topOuter},${bottom},${outerwear},${footwear},"${now}","${now}",1`;
    newRows.push(row);
  }

  // Append to file
  fs.appendFileSync(CSV_PATH, '\n' + newRows.join('\n'), 'utf-8');
  console.log(`✅ Appended ${newRows.length} rows to ${path.basename(CSV_PATH)}`);
}

main();
