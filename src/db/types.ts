/**
 * A single user interaction record (outfit save or flag).
 * 
 * This schema is designed to be forward-compatible:
 * - Required fields cover the current ML pipeline needs
 * - Optional fields (confidence, modelVersion, metadata) support future analytics
 * - user_id is a string to accommodate any auth system (UUID, integer, email, etc.)
 */
export interface InteractionRecord {
  // ── Identity ──────────────────────────────────────────────
  id?: number;                    // Auto-generated by DB
  userId: string;                 // Your auth system's user identifier
  
  // ── Interaction Type ──────────────────────────────────────
  action: 'save' | 'flag';       // What the user did
  
  // ── Outfit Colors ─────────────────────────────────────────
  topColor: string;
  bottomColor: string;
  outerwearColor: string;
  footwearColor: string;
  topOuterColor: string;         // The predicted/selected midlayer color
  
  // ── Scoring ───────────────────────────────────────────────
  interactionScore: number;       // 2 = positive (save), 0 = negative (flag)
  confidenceScore?: number;       // Model's confidence when it made this prediction
  modelVersion?: string;          // Which model version generated this recommendation
  
  // ── Context ───────────────────────────────────────────────
  vibe?: string;                  // minimalist, streetwear, etc.
  occasion?: string;              // casual, formal, etc.
  fitType?: string;               // fitted, relaxed, etc.
  
  // ── Timestamps ────────────────────────────────────────────
  createdAt?: string;             // ISO 8601 timestamp (auto-set by DB)
  
  // ── Extensibility ─────────────────────────────────────────
  metadata?: Record<string, any>; // Any extra data your company wants to track
}

/**
 * Filters for querying interactions.
 */
export interface InteractionFilters {
  userId?: string;
  action?: 'save' | 'flag';
  startDate?: string;             // ISO 8601
  endDate?: string;               // ISO 8601
  limit?: number;
  offset?: number;
}

/**
 * One user's aggregated behavior for a single calendar month.
 * Stores RAW COUNTS (not normalized frequencies) so that repeated rollup
 * runs can merge additively without double-normalization errors.
 */
export interface UserProfileSummary {
  id?: number;
  userId: string;
  periodMonth: string;                                 // 'YYYY-MM'
  totalSaves: number;
  totalFlags: number;
  colorCounts: Record<string, number>;                 // saved midlayer color -> count
  slotCounts: Record<string, Record<string, number>>;  // slot -> color -> count
  contextCounts: Record<string, Record<string, number>>; // vibe/occasion/fitType -> value -> count
  updatedAt?: string;
}

/**
 * A user's merged profile across all summary months plus current (hot) rows.
 * This is the compact context used for next-month personalization.
 */
export interface UserProfile {
  userId: string;
  monthsSummarized: number;
  totalSaves: number;
  totalFlags: number;
  /** Normalized 0..1 affinity per midlayer color (share of the user's saves). */
  colorAffinity: Record<string, number>;
  /** Top saved midlayer colors, most preferred first. */
  favoriteColors: string[];
  /** Most frequent vibe / occasion / fitType, if any. */
  contextPreferences: Record<string, string | null>;
}

/**
 * Result of one rollup run (summarize + archive + prune).
 */
export interface RollupResult {
  cutoffDate: string;      // rows strictly older than this were processed
  rowsExamined: number;
  rowsArchived: number;    // appended to archive CSV files on disk
  rowsDeleted: number;     // pruned from the hot user_interactions table
  summariesUpserted: number;
  archiveFiles: string[];  // archive files written/appended this run
}

/**
 * Summary statistics about stored interactions.
 */
export interface InteractionStats {
  totalInteractions: number;
  totalSaves: number;
  totalFlags: number;
  uniqueUsers: number;
  oldestRecord?: string;
  newestRecord?: string;
}

/**
 * The contract every database adapter must implement.
 * 
 * IMPORTANT FOR COMPANY INTEGRATION:
 * When you build your own adapter (e.g., CompanyPostgresAdapter), you only
 * need to implement these methods. The route handlers, training pipeline,
 * and all other code stays untouched.
 */
export interface InteractionStore {
  /**
   * Initialize the store (create tables, verify connection, etc.)
   * Called once during server startup.
   */
  initialize(): Promise<void>;

  /**
   * Save a single user interaction.
   * Returns the created record with its auto-generated ID.
   */
  saveInteraction(record: Omit<InteractionRecord, 'id' | 'createdAt'>): Promise<InteractionRecord>;

  /**
   * Query interactions with optional filters.
   */
  getInteractions(filters?: InteractionFilters): Promise<InteractionRecord[]>;

  /**
   * Get all interactions for a specific user.
   */
  getInteractionsByUser(userId: string, limit?: number): Promise<InteractionRecord[]>;

  /**
   * Get summary statistics.
   */
  getStats(): Promise<InteractionStats>;

  /**
   * Export all 'save' interactions as a CSV file compatible with train.py.
   * Returns the path to the exported file.
   * 
   * The CSV format MUST match: session_id,top_color,bottom_color,outerwear_color,
   * footwear_color,predicted_color,interaction_score
   */
  exportForTraining(outputPath?: string): Promise<string>;

  /**
   * Delete all interactions for a specific user (GDPR compliance).
   * Returns the number of deleted records.
   */
  deleteUserInteractions(userId: string): Promise<number>;

  /**
   * Import records from an existing CSV file (one-time migration).
   * Returns the number of imported records.
   */
  importFromCSV(csvPath: string): Promise<number>;

  /**
   * Summarize, archive, and prune interactions older than `cutoffIso`:
   *   1. Append raw rows to per-month CSV archive files in `archiveDir`
   *      (kept for retraining — exportForTraining merges them back in).
   *   2. Merge per-user monthly counts into user_profile_summaries.
   *   3. Delete the archived rows from the hot user_interactions table.
   * Safe to run repeatedly; only rows older than the cutoff are touched.
   */
  rollupOldInteractions(cutoffIso: string, archiveDir: string): Promise<RollupResult>;

  /**
   * Get a user's merged profile (all summary months + live rows).
   * Returns null when the user has no history at all.
   */
  getUserProfile(userId: string): Promise<UserProfile | null>;

  /**
   * Clean up connections on shutdown.
   */
  close(): Promise<void>;
}
